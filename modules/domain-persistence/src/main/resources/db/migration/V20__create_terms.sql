-- V20: Terms of Service / Privacy Policy — append-only version management + user agreement tracking.

CREATE TABLE terms (
    id           BIGSERIAL PRIMARY KEY,
    type         VARCHAR(20)  NOT NULL,          -- 'TERMS' | 'PRIVACY'
    version      INT          NOT NULL,
    title        VARCHAR(200) NOT NULL,
    content      TEXT         NOT NULL,          -- plain text, newline-separated paragraphs
    is_current   BOOLEAN      NOT NULL DEFAULT FALSE,
    published_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX idx_terms_type_version ON terms(type, version);
CREATE INDEX idx_terms_type_current ON terms(type, is_current);

CREATE TABLE user_terms_agreements (
    id         BIGSERIAL PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    terms_id   BIGINT      NOT NULL REFERENCES terms(id),
    agreed_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ip_address VARCHAR(45)
);

CREATE INDEX idx_uta_user  ON user_terms_agreements(user_id);
CREATE INDEX idx_uta_terms ON user_terms_agreements(terms_id);

